<?php
defined('BASEPATH') OR exit('No direct script access allowed');

if (!function_exists('spider_chart'))
{
    function spider_chart($labels, $dataset1 = array(), $dataset2 = array())
    {
        /*
        |--------------------------------------------------------------------------
        | CHART SETTINGS
        |--------------------------------------------------------------------------
        */

        $svgWidth  = 600;
        $svgHeight = 600;

        /*
        |--------------------------------------------------------------------------
        | MAXIMUM SCORE
        |--------------------------------------------------------------------------
        */

        $maxScore = 10;

        /*
        |--------------------------------------------------------------------------
        | CHART CENTER
        |--------------------------------------------------------------------------
        */

        $cx = $svgWidth / 2;
        $cy = 285;

        /*
        |--------------------------------------------------------------------------
        | CHART RADIUS
        |--------------------------------------------------------------------------
        */

        $radius = 165;

        /*
        |--------------------------------------------------------------------------
        | NUMBER OF AXES
        |--------------------------------------------------------------------------
        */

        $count = count($labels);

        if ($count < 2)
        {
            return '';
        }

        /*
        |--------------------------------------------------------------------------
        | SVG START
        |--------------------------------------------------------------------------
        */

        $svg = '';

        $svg .= '<svg
            xmlns="http://www.w3.org/2000/svg"
            width="'.$svgWidth.'"
            height="'.$svgHeight.'"
            viewBox="0 0 '.$svgWidth.' '.$svgHeight.'">';


        /*
        |--------------------------------------------------------------------------
        | LEGEND
        |--------------------------------------------------------------------------
        */

        $legendItems = array();

        if (
            !empty($dataset1) &&
            isset($dataset1['values']) &&
            is_array($dataset1['values']) &&
            !empty($dataset1['values'])
        )
        {
            $legendItems[] = $dataset1;
        }

        if (
            !empty($dataset2) &&
            isset($dataset2['values']) &&
            is_array($dataset2['values']) &&
            !empty($dataset2['values'])
        )
        {
            $legendItems[] = $dataset2;
        }


        /*
        |--------------------------------------------------------------------------
        | LEGEND POSITION
        |--------------------------------------------------------------------------
        */

        $legendItemWidth = 120;

        $legendWidth = count($legendItems) * $legendItemWidth;

        $legendX = ($svgWidth - $legendWidth) / 2;

        foreach ($legendItems as $legend)
        {
            $legendColor = isset($legend['color'])
                ? $legend['color']
                : '#2196F3';

            $legendLabel = isset($legend['label'])
                ? $legend['label']
                : '';

            $svg .= '
            <rect
                x="'.$legendX.'"
                y="25"
                width="20"
                height="10"
                fill="'.$legendColor.'"/>

            <text
                x="'.($legendX + 27).'"
                y="35"
                font-family="Arial"
                font-size="12"
                fill="#000000">
                '.htmlspecialchars($legendLabel, ENT_QUOTES, 'UTF-8').'
            </text>';

            $legendX += $legendItemWidth;
        }


        /*
        |--------------------------------------------------------------------------
        | GRID - 1 TO 10
        |--------------------------------------------------------------------------
        */

        for ($r = 1; $r <= $maxScore; $r++)
        {
            $points = array();

            for ($i = 0; $i < $count; $i++)
            {
                $angle = deg2rad(
                    -90 + ($i * 360 / $count)
                );

                $distance = $radius * ($r / $maxScore);

                $x = $cx + cos($angle) * $distance;
                $y = $cy + sin($angle) * $distance;

                $points[] = $x . ',' . $y;
            }

            $svg .= '
            <polygon
                points="'.implode(' ', $points).'"
                fill="none"
                stroke="#C8C8C8"
                stroke-width="1"/>';
        }


        /*
        |--------------------------------------------------------------------------
        | AXIS LINES
        |--------------------------------------------------------------------------
        */

        for ($i = 0; $i < $count; $i++)
        {
            $angle = deg2rad(
                -90 + ($i * 360 / $count)
            );

            $x = $cx + cos($angle) * $radius;
            $y = $cy + sin($angle) * $radius;

            $svg .= '
            <line
                x1="'.$cx.'"
                y1="'.$cy.'"
                x2="'.$x.'"
                y2="'.$y.'"
                stroke="#B8B8B8"
                stroke-width="1"/>';
        }


        /*
        |--------------------------------------------------------------------------
        | SCALE NUMBERS 1 TO 10 ON EVERY AXIS
        |--------------------------------------------------------------------------
        */

        for ($i = 0; $i < $count; $i++)
        {
            $angle = deg2rad(
                -90 + ($i * 360 / $count)
            );

            for ($r = 1; $r <= $maxScore; $r++)
            {
                $distance = $radius * ($r / $maxScore);

                $numberX = $cx + cos($angle) * $distance;
                $numberY = $cy + sin($angle) * $distance;

                /*
                |--------------------------------------------------------------------------
                | Keep numbers slightly away from axis line
                |--------------------------------------------------------------------------
                */

                $perpendicularX = -sin($angle) * 7;
                $perpendicularY = cos($angle) * 7;

                $numberX += $perpendicularX;
                $numberY += $perpendicularY;

                /*
                |--------------------------------------------------------------------------
                | Small vertical adjustment
                |--------------------------------------------------------------------------
                */

                $numberY += 3;

                $svg .= '
                <text
                    x="'.$numberX.'"
                    y="'.$numberY.'"
                    font-family="Arial"
                    font-size="9"
                    fill="#666666"
                    text-anchor="middle">
                    '.$r.'
                </text>';
            }
        }


        /*
        |--------------------------------------------------------------------------
        | CENTER 0
        |--------------------------------------------------------------------------
        */

        $svg .= '
        <text
            x="'.($cx + 8).'"
            y="'.($cy + 4).'"
            font-family="Arial"
            font-size="9"
            fill="#666666">
            0
        </text>';


        /*
        |--------------------------------------------------------------------------
        | DYNAMIC AXIS LABELS
        |--------------------------------------------------------------------------
        */

        for ($i = 0; $i < $count; $i++)
        {
            $angle = deg2rad(
                -90 + ($i * 360 / $count)
            );

            /*
            |--------------------------------------------------------------------------
            | Label distance from chart
            |--------------------------------------------------------------------------
            */

            $labelDistance = $radius + 48;

            $labelX = $cx + cos($angle) * $labelDistance;
            $labelY = $cy + sin($angle) * $labelDistance;

            /*
            |--------------------------------------------------------------------------
            | Text alignment
            |--------------------------------------------------------------------------
            */

            $anchor = 'middle';

            if (cos($angle) > 0.30)
            {
                $anchor = 'start';
            }
            elseif (cos($angle) < -0.30)
            {
                $anchor = 'end';
            }

            /*
            |--------------------------------------------------------------------------
            | Vertical adjustment
            |--------------------------------------------------------------------------
            */

            $labelY += 5;

            /*
            |--------------------------------------------------------------------------
            | Label
            |--------------------------------------------------------------------------
            */

            $label = htmlspecialchars(
                $labels[$i],
                ENT_QUOTES,
                'UTF-8'
            );

            $svg .= '
            <text
                x="'.$labelX.'"
                y="'.$labelY.'"
                font-family="Arial"
                font-size="12"
                font-weight="bold"
                fill="#000000"
                text-anchor="'.$anchor.'">
                '.$label.'
            </text>';
        }


        /*
        |--------------------------------------------------------------------------
        | FUNCTION TO DRAW DATASET
        |--------------------------------------------------------------------------
        */

        $drawDataset = function($dataset) use (
            $cx,
            $cy,
            $radius,
            $count,
            $maxScore
        )
        {
            $result = '';

            /*
            |--------------------------------------------------------------------------
            | Validate Dataset
            |--------------------------------------------------------------------------
            */

            if (
                empty($dataset) ||
                !isset($dataset['values']) ||
                !is_array($dataset['values']) ||
                count($dataset['values']) != $count
            )
            {
                return $result;
            }

            /*
            |--------------------------------------------------------------------------
            | Color
            |--------------------------------------------------------------------------
            */

            $color = isset($dataset['color'])
                ? $dataset['color']
                : '#2196F3';

            /*
            |--------------------------------------------------------------------------
            | Points
            |--------------------------------------------------------------------------
            */

            $points = array();

            foreach ($dataset['values'] as $k => $v)
            {
                /*
                |--------------------------------------------------------------------------
                | Convert value to number
                |--------------------------------------------------------------------------
                */

                $v = (float)$v;

                /*
                |--------------------------------------------------------------------------
                | Limit score from 0 to 10
                |--------------------------------------------------------------------------
                */

                if ($v < 0)
                {
                    $v = 0;
                }

                if ($v > $maxScore)
                {
                    $v = $maxScore;
                }

                /*
                |--------------------------------------------------------------------------
                | Calculate angle
                |--------------------------------------------------------------------------
                */

                $angle = deg2rad(
                    -90 + ($k * 360 / $count)
                );

                /*
                |--------------------------------------------------------------------------
                | Calculate distance
                |--------------------------------------------------------------------------
                */

                $distance = $radius * ($v / $maxScore);

                /*
                |--------------------------------------------------------------------------
                | Calculate point
                |--------------------------------------------------------------------------
                */

                $x = $cx + cos($angle) * $distance;
                $y = $cy + sin($angle) * $distance;

                $points[] = $x . ',' . $y;
            }


            /*
            |--------------------------------------------------------------------------
            | DATA AREA
            |--------------------------------------------------------------------------
            */

            $result .= '
            <polygon
                points="'.implode(' ', $points).'"
                fill="'.$color.'"
                fill-opacity="0.35"
                stroke="'.$color.'"
                stroke-width="3"
                stroke-opacity="1"/>';


            /*
            |--------------------------------------------------------------------------
            | DATA POINTS
            |--------------------------------------------------------------------------
            */

            foreach ($points as $point)
            {
                $pointArray = explode(',', $point);

                $px = $pointArray[0];
                $py = $pointArray[1];

                $result .= '
                <circle
                    cx="'.$px.'"
                    cy="'.$py.'"
                    r="4"
                    fill="'.$color.'"/>';
            }

            return $result;
        };


        /*
        |--------------------------------------------------------------------------
        | CYCLE 1
        |--------------------------------------------------------------------------
        */

        $svg .= $drawDataset($dataset1);


        /*
        |--------------------------------------------------------------------------
        | CYCLE 2
        |--------------------------------------------------------------------------
        */

        $svg .= $drawDataset($dataset2);


        /*
        |--------------------------------------------------------------------------
        | CLOSE SVG
        |--------------------------------------------------------------------------
        */

        $svg .= '</svg>';

        return $svg;
    }
}